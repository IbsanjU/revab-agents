/**
 * The `revab` command for VS Code's integrated terminals.
 *
 * `npx revab` only works inside a built checkout, and in bundled mode there is no checkout and no
 * `revab` on PATH at all, so typing `revab` said "not found". The extension writes a tiny launcher
 * into its own storage and puts that folder on the PATH of terminals it opens. The launcher runs
 * the same CLI the gateway uses, with whichever node and entry file the extension resolved.
 *
 * `doctor` and `start` read `.env`, `projects/` and `knowledge/` from the working directory, so
 * the launcher moves into the home folder for those two; every other command runs where you are.
 * Pure (no `vscode`): every rule, including shell quoting, is unit tested.
 */

export interface ShimInput {
  platform: NodeJS.Platform;
  node: string;
  /** Arguments that run the CLI: the entry file, preceded by loader flags if any (no sub-command). */
  cliArgs: string[];
  home: string;
}

/** Commands that must run inside the home folder. */
export const HOME_COMMANDS = ["doctor", "start"] as const;

export const shimFileName = (platform: NodeJS.Platform): string => (platform === "win32" ? "revab.cmd" : "revab");

/** `launchArgs` from the gateway launch end with the `start` sub-command; the CLI entry is the rest. */
export function cliArgsFrom(launchArgs: readonly string[]): string[] {
  return launchArgs[launchArgs.length - 1] === "start" ? launchArgs.slice(0, -1) : [...launchArgs];
}

const posixQuote = (s: string): string => `'${s.replace(/'/g, `'\\''`)}'`;

function windowsQuote(s: string): string {
  if (/["\r\n]/.test(s)) throw new Error(`cannot create a Windows launcher for a path containing a quote or newline: ${s}`);
  return `"${s.replace(/%/g, "%%")}"`;
}

export function shimContent(input: ShimInput): string {
  if (input.platform === "win32") {
    const q = windowsQuote;
    return [
      "@echo off",
      "rem Generated by the revab VS Code extension. It is rewritten each time the extension starts.",
      ...HOME_COMMANDS.map((c) => `if /I "%~1"=="${c}" cd /d ${q(input.home)}`),
      `${q(input.node)} ${input.cliArgs.map(q).join(" ")} %*`,
      "",
    ].join("\r\n");
  }
  const q = posixQuote;
  return [
    "#!/bin/sh",
    "# Generated by the revab VS Code extension. It is rewritten each time the extension starts.",
    'case "$1" in',
    `  ${HOME_COMMANDS.join("|")}) cd ${q(input.home)} || exit 1 ;;`,
    "esac",
    `exec ${q(input.node)} ${input.cliArgs.map(q).join(" ")} "$@"`,
    "",
  ].join("\n");
}
